#!/usr/bin/env python3
"""Build the static, offline-ready Rome itinerary content bundle.

Requires Python Markdown (the `markdown` package). Source-of-truth files live in
content/rome-2026/{ko,en,zh,ja}/. The output is committed so the page works
without a runtime dependency or network connection.
"""
from __future__ import annotations

import json
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / "content" / "rome-2026"
OUTPUT = ROOT / "js" / "rome-itinerary-content.js"
LANGUAGES = ("ko", "en", "zh", "ja")
DOCUMENTS = {
    "master": "master_schedule.md",
    "strike": "strike_guide.md",
}
EXTENSIONS = ["tables", "fenced_code", "sane_lists", "toc"]


def main() -> None:
    bundle: dict[str, dict[str, str]] = {}
    for language in LANGUAGES:
        bundle[language] = {}
        for key, filename in DOCUMENTS.items():
            source = SOURCE_ROOT / language / filename
            if not source.is_file():
                raise SystemExit(f"Missing source: {source}")
            text = source.read_text(encoding="utf-8")
            if not text.strip():
                raise SystemExit(f"Empty source: {source}")
            bundle[language][key] = markdown.markdown(text, extensions=EXTENSIONS)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text(
        "/* Generated by tools/build_rome_itinerary_content.py; edit the Markdown sources, not this bundle. */\n"
        f"window.ROME_ITINERARY_CONTENT = {serialized};\n",
        encoding="utf-8",
    )
    print(f"Built {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size:,} bytes)")
    print(f"Languages: {', '.join(LANGUAGES)}; documents per language: {len(DOCUMENTS)}")


if __name__ == "__main__":
    main()
